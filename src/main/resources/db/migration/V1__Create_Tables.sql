CREATE TABLE tb_fichas(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_aula DATE NOT NULL,
    avaliacao_power_house VARCHAR(255) NOT NULL,
    condicao_dor_chegada VARCHAR(255) NOT NULL,
    localizacao_dor_chegada VARCHAR(255),
    escala_dor INTEGER,
    condicao_dor_final VARCHAR(255) NOT NULL,
    observacoes TEXT,
    aluno_id INTEGER NOT NULL,
    professor_id INTEGER NOT NULL,

    CONSTRAINT fk_ficha_aluno
                      FOREIGN KEY (aluno_id)
                      REFERENCES tb_aluno(id),

    CONSTRAINT fk_ficha_professor
                      FOREIGN KEY (professor_id)
                      REFERENCES tb_professor(id)
);

CREATE TABLE tb_aparelhos_ficha(
    ficha_aula_id INTEGER NOT NULL,
    aparelho VARCHAR(255) NOT NULL,

    CONSTRAINT fk_aparelhos_ficha
                               FOREIGN KEY (ficha_aula_id)
                               REFERENCES tb_fichas(id),

    CONSTRAINT uk_aparelho_ficha
                               UNIQUE (ficha_aula_id, aparelho)
);

CREATE TABLE tb_atividades_ficha(
    ficha_aula_id INTEGER NOT NULL,
    regiao_corporal VARCHAR(255) NOT NULL,
    tipo_atividade VARCHAR(255) NOT NULL,

    CONSTRAINT fk_atividades_ficha
                                FOREIGN KEY (ficha_aula_id)
                                REFERENCES tb_fichas(id),

    CONSTRAINT uk_atividade_ficha
                                UNIQUE (ficha_aula_id, regiao_corporal, tipo_atividade)
);